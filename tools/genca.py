#!/usr/bin/env python3
"""Embeds a CA bundle into source/ca_bundle.h (PEM as a raw string literal)."""
import os
import sys

candidates = [
    os.path.join(os.path.dirname(__file__), "..", "data", "ca_bundle.pem"),
    "/etc/ssl/certs/ca-certificates.crt",
    "/etc/pki/tls/certs/ca-bundle.crt",
    "/etc/ssl/cert.pem",
]
path = next((p for p in candidates if os.path.isfile(p)), None)
if not path:
    print("error: no CA bundle found; put one in data/ca_bundle.pem", file=sys.stderr)
    sys.exit(1)

with open(path, "r", errors="replace") as f:
    pem = f.read()
if ")CABUNDLE\"" in pem:
    raise SystemExit("CA bundle contains raw string terminator")

out = os.path.join(os.path.dirname(__file__), "..", "source", "ca_bundle.h")
with open(out, "w") as f:
    f.write("// Auto-generated by tools/genca.py - do not edit.\n")
    f.write("#pragma once\n")
    f.write("static const char kCABundle[] = R\"CABUNDLE(")
    f.write(pem)
    f.write(")CABUNDLE\";\n")

print("embedded", path, len(pem), "bytes ->", out)
