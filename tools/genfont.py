#!/usr/bin/env python3
"""Generates source/font8x16.h - an 8x16 1bpp bitmap font for ASCII + Cyrillic."""
import os
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
W, H = 8, 16
SIZE = 14

codepoints = list(range(0x20, 0x7F))
codepoints += list(range(0x410, 0x450))  # А-я
codepoints += [0x401, 0x451]             # Ё, ё
codepoints += list(range(0x00A0, 0x0100))  # Latin-1 (·, ±, «, »)
codepoints += list(range(0x2010, 0x2030))  # dashes, quotes, …
codepoints += [0x2190, 0x2192, 0x2191, 0x2193, 0x25B6, 0x25A0, 0x2026, 0x00B7]
codepoints += [0x2665, 0x2666, 0x2713, 0x00D7, 0x2192]

font = ImageFont.truetype(FONT_PATH, SIZE)
glyphs = []
for cp in sorted(set(codepoints)):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    ch = chr(cp)
    bbox = d.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    x = (W - gw) // 2 - bbox[0]
    y = (H - (bbox[3] - bbox[1])) // 2 - bbox[1]
    d.text((x, y), ch, fill=255, font=font)
    rows = []
    for row in range(H):
        bits = 0
        for col in range(W):
            if img.getpixel((col, row)) > 96:
                bits |= 1 << (7 - col)
        rows.append(bits)
    glyphs.append((cp, rows))

out = os.path.join(os.path.dirname(__file__), "..", "source", "font8x16.h")
with open(out, "w") as f:
    f.write("// Auto-generated by tools/genfont.py - do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("typedef struct { uint16_t cp; uint8_t rows[16]; } Glyph8x16;\n")
    f.write("static const Glyph8x16 kFont8x16[] = {\n")
    for cp, rows in glyphs:
        f.write("  {0x%04X, {%s}},\n" % (cp, ",".join("0x%02X" % r for r in rows)))
    f.write("};\n")
    f.write("#define kFont8x16Count (sizeof(kFont8x16)/sizeof(kFont8x16[0]))\n")

print("wrote", out, len(glyphs), "glyphs")
# preview a few
for cp in (0x41, 0x5A, 0x410, 0x44F, 0x2665):
    rows = dict(glyphs)[cp]
    print("U+%04X %r" % (cp, chr(cp)))
    for r in rows:
        print("".join("#" if r & (1 << (7 - c)) else "." for c in range(W)))
